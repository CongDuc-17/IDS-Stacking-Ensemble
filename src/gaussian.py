"""Fit a benign-only diagonal Gaussian on chronological host windows or predefined flow splits."""
import argparse
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import classification_report, confusion_matrix
from sklearn.mixture import GaussianMixture

from host_features import HOST_FEATURES
from features import FEATURES


def host_matrix(frame, features=HOST_FEATURES):
    values = frame[features].apply(pd.to_numeric, errors="raise").to_numpy(dtype=float)
    if not len(values) or not np.isfinite(values).all() or (features == HOST_FEATURES and (values < 0).any()):
        raise ValueError("Features must be finite/nonempty; host counters must be nonnegative.")
    # Some raw flow datasets contain negative measurements. Preserve and disclose them, never clip silently.
    return np.sign(values) * np.log1p(np.abs(values))


def split_windows(frame):
    required = {"window_epoch", "host_ip", "window_seconds", "Label", *HOST_FEATURES}
    if required - set(frame) or frame.empty:
        raise ValueError("Missing host/window features, Label or empty input.")
    frame = frame.copy()
    frame["window_epoch"] = pd.to_numeric(frame.window_epoch, errors="raise")
    if not np.isfinite(frame.window_epoch).all() or (frame.window_epoch < 0).any():
        raise ValueError("Invalid window timestamps.")
    widths = pd.to_numeric(frame.window_seconds, errors="raise")
    if widths.nunique() != 1 or widths.isna().any() or not np.isfinite(widths).all() or widths.iloc[0] < 1:
        raise ValueError("Use one positive, finite window width throughout the experiment.")
    if (frame.window_epoch % widths.iloc[0] != 0).any() or frame.host_ip.isna().any():
        raise ValueError("Unaligned windows or missing host IDs.")
    if frame.duplicated(["window_epoch", "host_ip"]).any():
        raise ValueError("Duplicate host/window rows.")
    if not set(frame.Label) <= {"BENIGN", "ATTACK", "UNKNOWN"}:
        raise ValueError("Use BENIGN/ATTACK/UNKNOWN labels generated by host_features.py.")
    host_matrix(frame)
    windows = np.sort(frame.window_epoch.unique())
    if len(windows) < 5:
        raise ValueError("Need at least five distinct time windows for chronological train/validation/test.")
    train, val, test = np.split(windows, [int(len(windows) * .6), int(len(windows) * .8)])
    return tuple(frame.loc[frame.window_epoch.isin(part)].copy() for part in (train, val, test))


def fit_gaussian(train, validation, false_positive_rate=.01, features=HOST_FEATURES):
    if not 0 < false_positive_rate < 1:
        raise ValueError("Require 0 < false-positive-rate < 1.")
    if features == HOST_FEATURES and train.window_epoch.max() >= validation.window_epoch.min():
        raise ValueError("Training must precede validation without shared time windows.")
    normal_train = train.loc[train.Label == "BENIGN"]
    normal_val = validation.loc[validation.Label == "BENIGN"]
    if len(normal_train) < 5 or len(normal_val) < 3:
        raise ValueError("Need at least five BENIGN training rows and three BENIGN validation rows; collect independent benign periods.")
    model = GaussianMixture(n_components=1, covariance_type="diag", reg_covar=1e-4, random_state=42)
    model.fit(host_matrix(normal_train, features))
    scores = -model.score_samples(host_matrix(normal_val, features))
    threshold = float(np.quantile(scores, 1 - false_positive_rate, method="higher"))
    return {"model": model, "features": features, "threshold": threshold,
            "window_seconds": float(train.window_seconds.iloc[0]) if features == HOST_FEATURES else None,
            "validation_max_epoch": float(validation.window_epoch.max()) if features == HOST_FEATURES else None,
            "benign_train_rows": len(normal_train), "benign_validation_rows": len(normal_val),
            "target_validation_fpr": false_positive_rate}


def evaluate_gaussian(artifact, test):
    features = artifact["features"]
    if features not in (HOST_FEATURES, FEATURES):
        raise ValueError("Unknown Gaussian feature contract.")
    if features == HOST_FEATURES and not test.window_seconds.eq(artifact["window_seconds"]).all():
        raise ValueError("Host feature/window contract mismatch.")
    if features == HOST_FEATURES and test.window_epoch.min() <= artifact["validation_max_epoch"]:
        raise ValueError("Test windows must be later than all calibration windows.")
    scores = -artifact["model"].score_samples(host_matrix(test, features))
    predicted = np.where(scores > artifact["threshold"], "ATTACK", "BENIGN")
    known = test.Label.isin(["BENIGN", "ATTACK"])
    truth, pred = test.loc[known, "Label"].to_numpy(), predicted[known]
    tn, fp, fn, tp = confusion_matrix(truth, pred, labels=["BENIGN", "ATTACK"]).ravel()
    report = {"evaluated_rows": int(known.sum()), "unknown_rows_excluded": int((~known).sum()),
              "confusion_labels": ["BENIGN", "ATTACK"], "confusion_matrix": [[int(tn), int(fp)], [int(fn), int(tp)]],
              "false_positive_rate": float(fp / (fp + tn)) if fp + tn else None,
              "false_negative_rate": float(fn / (fn + tp)) if fn + tp else None,
              "classification_report": classification_report(truth, pred, labels=["BENIGN", "ATTACK"], zero_division=0, output_dict=True) if len(truth) else None}
    predictions = test[["window_epoch", "host_ip", "Label"] if features == HOST_FEATURES else ["Label"]].copy()
    predictions["anomaly_score"] = scores
    predictions["predicted_label"] = predicted
    return predictions, report


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", help="hosts.csv with ground truth; split by time windows")
    ap.add_argument("--train", help="Predefined training split (flow mode)")
    ap.add_argument("--validation", help="Predefined calibration split (flow mode)")
    ap.add_argument("--test", help="Predefined held-out split (flow mode)")
    ap.add_argument("--out", required=True, help="New experiment directory")
    ap.add_argument("--false-positive-rate", type=float, default=.01)
    args = ap.parse_args()
    try:
        target = Path(args.out)
        if target.exists():
            raise ValueError("Choose a new --out.")
        if args.data and not any((args.train, args.validation, args.test)):
            train, val, test = split_windows(pd.read_csv(args.data))
            features = HOST_FEATURES
            split_note = "60/20/20 chronological unique completion-time windows; all hosts in a window stay together"
        elif not args.data and all((args.train, args.validation, args.test)):
            train, val, test = [pd.read_csv(path) for path in (args.train, args.validation, args.test)]
            features = FEATURES
            split_note = "Predefined disjoint flow splits; inherits their sampling/session limitations"
            hashes = []
            for frame in (train, val, test):
                if not set(frame.Label) <= {"BENIGN", "ATTACK", "UNKNOWN"}:
                    raise ValueError("Flow mode requires binary ground truth.")
                host_matrix(frame, features)
                hashes.append(set(pd.util.hash_pandas_object(frame[features].astype(float), index=False)))
            if any(hashes[i] & hashes[j] for i in range(3) for j in range(i)):
                raise ValueError("Feature overlap across flow splits.")
        else:
            raise ValueError("Supply either --data hosts.csv or all of --train, --validation and --test flow splits.")
        artifact = fit_gaussian(train, val, args.false_positive_rate, features)
        predictions, report = evaluate_gaussian(artifact, test)
        target.mkdir(parents=True)
        joblib.dump(artifact, target / "gaussian.joblib")
        predictions.to_csv(target / "predictions.csv", index=False)
        for name, frame in (("train", train), ("validation", val), ("test", test)):
            frame.to_csv(target / f"{name}.csv", index=False)
        (target / "metrics.json").write_text(json.dumps(report, indent=2, allow_nan=False), encoding="utf-8")
        (target / "protocol.json").write_text(json.dumps({
            "arguments": vars(args), "features": features, "split": split_note,
            "threshold": artifact["threshold"], "target_validation_fpr": args.false_positive_rate,
            "fit": "One diagonal Gaussian on signed-log1p BENIGN train only; threshold from BENIGN validation only",
            "negative_measurements": {name: int((frame[features] < 0).sum().sum()) for name, frame in (("train", train), ("validation", val), ("test", test))},
            "benign_train_rows": artifact["benign_train_rows"], "benign_validation_rows": artifact["benign_validation_rows"],
            "limitations": ["Anomaly is not an attack type or a calibrated attack probability.",
                            "Window labels include endpoints/victims of attacks, not infected-host truth.",
                            "Temporal separation does not guarantee session/host independence."]
        }, indent=2, allow_nan=False), encoding="utf-8")
        print(json.dumps(report, indent=2))
    except (ValueError, KeyError) as error:
        ap.exit(1, f"Error: {error}\n")


if __name__ == "__main__":
    main()
